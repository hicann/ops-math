import sys
import numpy as np
import glob
import os

curr_dir = os.path.dirname(os.path.realpath(__file__))


def get_dtype_from_filename(filename):
    """Infer numpy dtype from filename prefix."""
    if "int32" in os.path.basename(filename):
        return np.int32
    return np.float32


def compare_data(golden_file_lists, output_file_lists, d_type):
    data_same = True
    for gold, out in zip(golden_file_lists, output_file_lists):
        np_dtype = get_dtype_from_filename(gold)
        tmp_out = np.fromfile(out, np_dtype)
        tmp_gold = np.fromfile(gold, np_dtype)

        if np_dtype == np.int32:
            # nlist: binary equal
            diff_idx = np.where(tmp_out != tmp_gold)[0]
        else:
            # float32: isclose with SE §5.5 tolerance (rtol=1e-4, atol=1e-8)
            diff_res = np.isclose(
                tmp_out, tmp_gold, rtol=1e-4, atol=1e-8, equal_nan=True
            )
            diff_idx = np.where(~diff_res)[0]

        if len(diff_idx) == 0:
            print(f"PASSED! {os.path.basename(out)}")
        else:
            print(f"FAILED! {os.path.basename(out)}")
            for idx in diff_idx[:5]:
                print(
                    f"  index: {idx}, output: {tmp_out[idx]}, golden: {tmp_gold[idx]}"
                )
            data_same = False
    return data_same


def get_file_lists(dtype):
    golden_file_lists = sorted(glob.glob(curr_dir + "/*golden*.bin"))
    output_file_lists = sorted(glob.glob(curr_dir + "/*output*.bin"))
    return golden_file_lists, output_file_lists


def process(d_type):
    golden_file_lists, output_file_lists = get_file_lists(d_type)
    if len(golden_file_lists) == 0:
        print("No golden files found!")
        return False
    if len(output_file_lists) == 0:
        print("No output files found!")
        return False
    if len(golden_file_lists) != len(output_file_lists):
        print(
            f"File count mismatch: golden={len(golden_file_lists)}, output={len(output_file_lists)}"
        )
        return False
    result = compare_data(golden_file_lists, output_file_lists, d_type)
    print("compare result:", result)
