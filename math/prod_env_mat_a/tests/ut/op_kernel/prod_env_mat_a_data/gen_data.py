def spline5_switch(nr_val, rmin, rmax):
    if nr_val < rmin:
        return 1.0, 0.0
    elif nr_val < rmax:
        uu = (nr_val - rmin) / (rmax - rmin)
        du = 1.0 / (rmax - rmin)
        sw = uu**3 * (-6.0 * uu**2 + 15.0 * uu - 10.0) + 1.0
        dsw = (
            3.0 * uu**2 * (-6.0 * uu**2 + 15.0 * uu - 10.0)
            + uu**3 * (-12.0 * uu + 15.0)
        ) * du
        return float(sw), float(dsw)
    else:
        return 0.0, 0.0


