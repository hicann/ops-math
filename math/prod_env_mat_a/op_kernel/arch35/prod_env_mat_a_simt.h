    descrpt_deriv[derivBase + idxDeriv + 1] = vv1 / dstd0;
    descrpt_deriv[derivBase + idxDeriv + 2] = vv2 / dstd0;
    descrpt_deriv[derivBase + idxDeriv + 3] = vv3 / dstd1;
    descrpt_deriv[derivBase + idxDeriv + 4] = vv4 / dstd1;
    descrpt_deriv[derivBase + idxDeriv + 5] = vv5 / dstd1;
