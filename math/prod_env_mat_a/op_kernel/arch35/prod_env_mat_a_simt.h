    float dstd0 = fmaxf(dstd[baseDavg], 1e-10f);
    float dstd1 = fmaxf(dstd[baseDavg + 1], 1e-10f);
    float dstd2 = fmaxf(dstd[baseDavg + 2], 1e-10f);
    float dstd3 = fmaxf(dstd[baseDavg + 3], 1e-10f);
