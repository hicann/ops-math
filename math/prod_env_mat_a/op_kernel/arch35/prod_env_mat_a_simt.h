    float vv4 = fmaf(2.0f * rx * ry * inr2, sw, -(dd1 * dswInr * ry));
    float vv5 = fmaf(2.0f * rx * rz * inr2, sw, -(dd1 * dswInr * rz));
    float vv6 = fmaf(2.0f * ry * rx * inr2, sw, -(dd2 * dswInr * rx));
    float vv7 = fmaf(DiagTerm(ry, inr2, inr), sw, -(dd2 * dswInr * ry));
    float vv8 = fmaf(2.0f * ry * rz * inr2, sw, -(dd2 * dswInr * rz));
    float vv9 = fmaf(2.0f * rz * rx * inr2, sw, -(dd3 * dswInr * rx));
    float vv10 = fmaf(2.0f * rz * ry * inr2, sw, -(dd3 * dswInr * ry));
    float vv11 = fmaf(DiagTerm(rz, inr2, inr), sw, -(dd3 * dswInr * rz));
