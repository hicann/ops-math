// 从 dim 属性解析 reduce 轴到 int64 数组：
//   dim 为空 → all reduce（dim = [0..xRank-1]，与 tiling::ParseDimAttr 一致）；
//   否则归一化负数到 [0, xRank)，重复/越界返回 false。
static bool LoadDimFromAttr(const gert::RuntimeAttrs* attrs, int64_t xRank, std::vector<int64_t>& axesOut,
                            std::string& errMsg)
{
    const auto* dimVec = attrs->GetListInt(ATTR_DIM_IDX);
    const int64_t dimNum = (dimVec == nullptr) ? 0 : static_cast<int64_t>(dimVec->GetSize());

    if (dimNum == 0) {
        axesOut.resize(static_cast<size_t>(xRank));
        for (int64_t i = 0; i < xRank; ++i) {
            axesOut[static_cast<size_t>(i)] = i;
        }
        return true;
    }

    const int64_t* data = dimVec->GetData();
    if (data == nullptr) {
        errMsg = "dim attr data ptr is null";
        return false;
    }
    std::set<int64_t> seen;
    axesOut.reserve(static_cast<size_t>(dimNum));
    for (int64_t i = 0; i < dimNum; ++i) {
        const int64_t v = data[i];
        if (v < -xRank || v >= xRank) {
            errMsg = "dim[" + std::to_string(i) + "]=" + std::to_string(v) + " out of range [-" +
                     std::to_string(xRank) + ", " + std::to_string(xRank) + ")";
            return false;
        }
        const int64_t norm = (v < 0) ? (v + xRank) : v;
        if (!seen.insert(norm).second) {
            errMsg = "duplicate dim " + std::to_string(norm) + " (idx=" + std::to_string(i) + ")";
            return false;
        }
        axesOut.push_back(norm);
    }
    return true;
}

static bool ReadKeepDim(const gert::RuntimeAttrs* attrs)
{
    const bool* p = attrs->GetAttrPointer<bool>(ATTR_KEEP_DIM_IDX);
    return (p == nullptr) ? KEEP_DIM_DEFAULT : *p;
}

static ge::graphStatus HandleScalarInput(gert::InferShapeContext* context, const gert::Shape* xShape,
                                         gert::Shape* yShape)
{
    if (xShape->GetDimNum() != 0) {
        return GRAPH_SUCCESS;
    }
    auto attrs = context->GetAttrs();
    OP_CHECK_NULL_WITH_CONTEXT(context, attrs);
    const bool keepDim = ReadKeepDim(attrs);
    if (keepDim) {
        *yShape = gert::Shape({1});
    } else {
        *yShape = gert::Shape();
    }
    OP_LOGD(context->GetNodeName(), "scalar input: keepDim=%d, yShape dims=%zu", static_cast<int>(keepDim),
            yShape->GetDimNum());
    return GRAPH_SUCCESS;
}

static ge::graphStatus InferShape4ReduceStdWithMean(gert::InferShapeContext* context)
{
    OP_LOGD(context->GetNodeName(), "Begin InferShape4ReduceStdWithMean");

    const gert::Shape* xShape = context->GetInputShape(INPUT_X_IDX);
    OP_CHECK_NULL_WITH_CONTEXT(context, xShape);
    gert::Shape* yShape = context->GetOutputShape(OUTPUT_Y_IDX);
    OP_CHECK_NULL_WITH_CONTEXT(context, yShape);

    // 1) unknown rank 透传
    if (IsUnknownRank(*xShape)) {
        SetUnknownRank(*yShape);
        OP_LOGD(context->GetNodeName(), "x is unknown rank; set y as unknown rank");
        return GRAPH_SUCCESS;
    }
    const int64_t xRank = static_cast<int64_t>(xShape->GetDimNum());

    // 1.5) rank 上界守卫：xRank 来自外部 shape，后续 isReduce[MAX_SUPPORTED_RANK] 按其索引访问，
    //      必须先拦截 rank>MAX_SUPPORTED_RANK，避免栈数组越界读写（与 L2 aclnn 路径 OP_CHECK_MAX_DIM 对齐）。
    if (xRank > static_cast<int64_t>(MAX_SUPPORTED_RANK)) {
        OP_LOGE(context->GetNodeName(), "xRank=%ld exceeds max supported rank %zu", xRank, MAX_SUPPORTED_RANK);
        return GRAPH_FAILED;
    }

    // 2) scalar (0-D) input
    if (xRank == 0) {
        return HandleScalarInput(context, xShape, yShape);
    }

    // 3) 读取属性 dim / keepdim
    auto attrs = context->GetAttrs();
    OP_CHECK_NULL_WITH_CONTEXT(context, attrs);
    const bool keepDim = ReadKeepDim(attrs);

    std::vector<int64_t> axes;
    std::string errMsg;
    if (!LoadDimFromAttr(attrs, xRank, axes, errMsg)) {
        OP_LOGE(context->GetNodeName(), "%s; xRank=%ld", errMsg.c_str(), xRank);
        return GRAPH_FAILED;
    }

    // 4) 计算输出 shape：keepDim=false 删除 reduce 轴；keepDim=true 置 1（axes 已归一化、无重复、无越界）
    bool isReduce[MAX_SUPPORTED_RANK] = {}; // xRank<=MAX_SUPPORTED_RANK 已由上方守卫保证
    for (int64_t a : axes) {
        isReduce[static_cast<size_t>(a)] = true;
    }
    yShape->SetDimNum(0);
    for (int64_t i = 0; i < xRank; ++i) {
        if (isReduce[static_cast<size_t>(i)]) {
            if (keepDim) {
                yShape->AppendDim(1);
            }
        } else {
            yShape->AppendDim(xShape->GetDim(static_cast<size_t>(i)));
        }
    }
    // 全轴归约且 keepDim=false → 标量（0-D，DimNum=0）
    OP_LOGD(context->GetNodeName(), "End InferShape: keepDim=%d, xRank=%ld, dim.size=%zu, outDim=%zu",
            static_cast<int>(keepDim), xRank, axes.size(), yShape->GetDimNum());
    return GRAPH_SUCCESS;
}

