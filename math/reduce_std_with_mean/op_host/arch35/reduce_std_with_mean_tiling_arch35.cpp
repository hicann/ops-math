static ge::graphStatus ParseDimAttr(gert::TilingContext* context, ReduceStdWithMeanCtx& ctx)
{
    const gert::RuntimeAttrs* attrs = context->GetAttrs();
    OP_CHECK_NULL_WITH_CONTEXT(context, attrs);
    const auto* dimVec = attrs->GetListInt(ATTR_DIM_IDX);
    const int64_t dimNum = (dimVec == nullptr) ? 0 : static_cast<int64_t>(dimVec->GetSize());
    const int64_t xRank = static_cast<int64_t>(ctx.xShape.size());
    ctx.reduceAxes.clear();

    if (dimNum == 0) {
        // dim=[] → dim=[0..xRank-1]，归约全部维度
        ctx.reduceAxes.reserve(static_cast<size_t>(xRank));
        for (int64_t i = 0; i < xRank; ++i) {
            ctx.reduceAxes.push_back(i);
        }
        return ge::GRAPH_SUCCESS;
    }

    const int64_t* data = dimVec->GetData();
    OP_CHECK_NULL_WITH_CONTEXT(context, data);
    std::set<int64_t> seen;
    for (int64_t i = 0; i < dimNum; ++i) {
        const int64_t v = data[i];
        if (v < -xRank || v >= xRank) {
            OP_LOGE_FOR_INVALID_VALUE_WITH_REASON(
                context->GetNodeName(), "dim", std::to_string(v).c_str(),
                "each dim must be in range [-" + std::to_string(xRank) + ", " + std::to_string(xRank) + ")");
            return ge::GRAPH_FAILED;
        }
        const int64_t norm = (v < 0) ? (v + xRank) : v;
        if (!seen.insert(norm).second) {
            OP_LOGE_FOR_INVALID_VALUE_WITH_REASON(
                context->GetNodeName(), "dim", std::to_string(v).c_str(),
                "duplicate axes are not allowed (axis " + std::to_string(norm) + " appears more than once)");
            return ge::GRAPH_FAILED;
        }
        ctx.reduceAxes.push_back(norm);
    }
    std::sort(ctx.reduceAxes.begin(), ctx.reduceAxes.end());
    return ge::GRAPH_SUCCESS;
}

// 读取 post-op 标量属性（invert / epsilon / correction）并计算 N / invN / invDenomStd。
//   N = ∏(reduce 轴的原始 x size)；invDenomStd = 1/max(0, N-correction)（invert=false 分母）。
static ge::graphStatus ComputePostOpScalars(gert::TilingContext* context, ReduceStdWithMeanCtx& ctx)
{
    const gert::RuntimeAttrs* attrs = context->GetAttrs();
    const bool* invertP = (attrs == nullptr) ? nullptr : attrs->GetBool(ATTR_INVERT_IDX);
    const float* epsP = (attrs == nullptr) ? nullptr : attrs->GetFloat(ATTR_EPSILON_IDX);
    const int64_t* corrP = (attrs == nullptr) ? nullptr : attrs->GetInt(ATTR_CORRECTION_IDX);
    ctx.invert = (invertP != nullptr && *invertP) ? 1U : 0U;
    ctx.epsilon = (epsP != nullptr) ? *epsP : EPSILON_DEFAULT;
    ctx.correction = (corrP != nullptr) ? *corrP : CORRECTION_DEFAULT;

    // correction 值域校验：须为非负整数（与 L2 aclnn CheckParams 对齐）
    if (ctx.correction < 0) {
        OP_LOGE_FOR_INVALID_VALUE(context->GetNodeName(), "correction", std::to_string(ctx.correction).c_str(),
                                  "a non-negative integer");
        return ge::GRAPH_FAILED;
    }

    int64_t n = 1;
    for (int64_t a : ctx.reduceAxes) {
        n *= ctx.xShape[static_cast<size_t>(a)];
    }
    ctx.totalN = (n > 0) ? n : 1;
    ctx.invN = 1.0f / static_cast<float>(ctx.totalN);
    const int64_t denom = ctx.totalN - ctx.correction;
    ctx.invDenomStd = (denom > 0) ?
                          (1.0f / static_cast<float>(denom)) :
                          std::numeric_limits<float>::infinity(); // N<=correction → +Inf/NaN（与 golden 对齐）
    return ge::GRAPH_SUCCESS;
}

// 把 x 的 shape 与 reduceAxes 合成「轴列表 + R 标记」（pattern 预处理的初态）
