#include "register/op_impl_registry.h"
#include "op_common/log/log.h"
#include <cstddef>
#include <cmath>

namespace ge {
namespace {
constexpr size_t INPUT_INDEX = 0;
constexpr size_t OUTPUT_INDEX = 0;
constexpr size_t START_ATTR_INDEX = 0;
constexpr size_t END_ATTR_INDEX = 1;
constexpr size_t STEPS_ATTR_INDEX = 2;
constexpr size_t BASE_ATTR_INDEX = 3;

graphStatus InferShapeFailure(const char* nodeName, const char* reason)
{
    OP_LOGE(nodeName, "LogSpaceD InferShape failed: %s", reason);
    return GRAPH_FAILED;
}
} // namespace

graphStatus InferShape(gert::InferShapeContext* context)
{
    if (context == nullptr) {
        return InferShapeFailure("LogSpaceD", "infer-shape context is null");
    }

    const gert::Shape* inputShape = context->GetInputShape(INPUT_INDEX);
    gert::Shape* outputShape = context->GetOutputShape(OUTPUT_INDEX);
    const gert::RuntimeAttrs* attrs = context->GetAttrs();
    if (inputShape == nullptr || outputShape == nullptr || attrs == nullptr) {
        return InferShapeFailure(context->GetNodeName(), "input shape, output shape, or runtime attributes is null");
    }
    OP_LOGI(context->GetNodeName(), "LogSpaceD TARGET_V2 InferShape entered rank=%zu", inputShape->GetDimNum());

    const int64_t* stepsAttr = attrs->GetInt(STEPS_ATTR_INDEX);
    if (stepsAttr == nullptr) {
        return InferShapeFailure(context->GetNodeName(), "steps attribute is missing");
    }
    if (*stepsAttr < 0) {
        OP_LOGE(context->GetNodeName(), "LogSpaceD InferShape rejects negative steps=%ld",
                static_cast<long>(*stepsAttr));
        return GRAPH_FAILED;
    }
    const float* startAttr = attrs->GetFloat(START_ATTR_INDEX);
    const float* endAttr = attrs->GetFloat(END_ATTR_INDEX);
    const float* baseAttr = attrs->GetFloat(BASE_ATTR_INDEX);
    if (startAttr == nullptr || endAttr == nullptr || baseAttr == nullptr) {
        return InferShapeFailure(context->GetNodeName(), "start, end, or base attribute is missing");
    }
    if (!std::isfinite(*startAttr) || !std::isfinite(*endAttr) || !std::isfinite(*baseAttr)) {
        OP_LOGE(context->GetNodeName(), "LogSpaceD InferShape requires finite start=%f end=%f base=%f", *startAttr,
                *endAttr, *baseAttr);
        return GRAPH_FAILED;
    }

    const bool unknownRank = inputShape->GetDimNum() == 1 && inputShape->GetDim(0) == ge::UNKNOWN_DIM_NUM;
    if (!unknownRank) {
        if (inputShape->GetDimNum() != 1) {
            OP_LOGE(context->GetNodeName(), "LogSpaceD InferShape supports rank 1, got rank=%zu",
                    inputShape->GetDimNum());
            return GRAPH_FAILED;
        }
        const int64_t inputLength = inputShape->GetDim(0);
        if (inputLength != ge::UNKNOWN_DIM && inputLength != 1) {
            OP_LOGE(context->GetNodeName(), "LogSpaceD InferShape requires input shape [1], got dim0=%ld",
                    static_cast<long>(inputLength));
            return GRAPH_FAILED;
        }
    }

    outputShape->SetDimNum(1);
    outputShape->SetDim(0, *stepsAttr);
    OP_LOGI(context->GetNodeName(), "LogSpaceD TARGET_V2 inferred y=[%ld]", static_cast<long>(*stepsAttr));
    return GRAPH_SUCCESS;
}

} // namespace ge

