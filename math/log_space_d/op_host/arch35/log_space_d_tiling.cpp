bool ComputeLogSpaceDTiling(const LogSpaceDTilingInputs& inputs, LogSpaceDTilingData& output, const char*& errorMessage)
{
    errorMessage = nullptr;
    if (inputs.dim0 <= 0 || inputs.availableCoreNum == 0 || inputs.usableUbBytes == 0 ||
        inputs.usableUbBytes > static_cast<std::uint64_t>(std::numeric_limits<std::int64_t>::max())) {
        return SetError("invalid dimension, core count, or UB size", errorMessage);
    }
    if (inputs.storageElemBytes != sizeof(std::uint16_t) && inputs.storageElemBytes != sizeof(float)) {
        return SetError("storage element size is not 2 or 4 bytes", errorMessage);
    }

    LogSpaceDTilingData computed{};
    computed.dim0 = inputs.dim0;
    computed.storageElemBytes = inputs.storageElemBytes;
    // Assist is only an ABI/dtype carrier. The active kernel owns two output
    // queue slots and two FP32 work buffers, with no input queue.
    computed.bufferBytesPerElem = kOutputQueueDepth * inputs.storageElemBytes + kFp32WorkBufferCount * sizeof(float);

    const std::int64_t usableUbBytes = static_cast<std::int64_t>(inputs.usableUbBytes);
    const std::int64_t ubAlignElems = kVfIndexAlignBytes / inputs.storageElemBytes;
    const std::int64_t maxElems = usableUbBytes / computed.bufferBytesPerElem;
    const std::int64_t maxVfTileElems = (kMaxVectorIndex / ubAlignElems) * ubAlignElems;
    computed.ubFormer = std::min((maxElems / ubAlignElems) * ubAlignElems, maxVfTileElems);
    std::int64_t allocatedUbBytes = 0;
    if (computed.ubFormer <= 0 || !MulChecked(computed.ubFormer, computed.bufferBytesPerElem, allocatedUbBytes) ||
        allocatedUbBytes > usableUbBytes) {
        return SetError("UB cannot hold an aligned vector tile", errorMessage);
    }

    const std::int64_t minElemsPerCore = kMinBytesPerCore / inputs.storageElemBytes;
    const std::int64_t wantedCores = inputs.dim0 / minElemsPerCore;
    computed.coreNum = std::min<std::int64_t>(std::max<std::int64_t>(1, wantedCores),
                                              static_cast<std::int64_t>(inputs.availableCoreNum));

    std::int64_t averageElems = 0;
    if (!CeilDivChecked(inputs.dim0, computed.coreNum, averageElems) ||
        !AlignUpChecked(averageElems, kBlockAlignElems, computed.blockFormer) ||
        !CeilDivChecked(inputs.dim0, computed.blockFormer, computed.blockNum) || computed.blockNum <= 0) {
        return SetError("failed to derive aligned block partition", errorMessage);
    }
    if (computed.blockNum > kMaxSimdBlockCount) {
        return SetError("block count exceeds the SIMD launch limit", errorMessage);
    }
    std::int64_t formerBlockTotal = 0;
    if (!MulChecked(computed.blockNum - 1, computed.blockFormer, formerBlockTotal) || formerBlockTotal >= inputs.dim0) {
        return SetError("block partition overflowed the output length", errorMessage);
    }
    computed.blockTail = inputs.dim0 - formerBlockTotal;

    if (!ComputeLoopAndTail(computed.blockFormer, computed.ubFormer, computed.ubLoopOfFormerBlock,
                            computed.ubTailOfFormerBlock) ||
        !ComputeLoopAndTail(computed.blockTail, computed.ubFormer, computed.ubLoopOfTailBlock,
                            computed.ubTailOfTailBlock)) {
        return SetError("failed to derive UB loop and tail counts", errorMessage);
    }

    output = computed;
    return true;
}

