// The block and vector limits are imposed by the arch35 kernel ABI rather than
// by a particular input dtype.  Dtype-dependent values are supplied through
// LogSpaceDTilingInputs.
constexpr std::int64_t kBlockAlignElems = 512;
constexpr std::int64_t kMinBytesPerCore = 16 * 1024;
constexpr std::int64_t kMaxVectorIndex = std::numeric_limits<std::uint16_t>::max();
constexpr std::int64_t kVfIndexAlignBytes = 256;
constexpr std::int64_t kOutputQueueDepth = 2;
constexpr std::int64_t kFp32WorkBufferCount = 2;
constexpr std::int64_t kMaxSimdBlockCount = std::numeric_limits<std::uint32_t>::max();

bool CeilDivChecked(std::int64_t value, std::int64_t divisor, std::int64_t& result)
{
    if (value < 0 || divisor <= 0) {
        return false;
    }
    result = value / divisor + (value % divisor == 0 ? 0 : 1);
    return true;
}

bool MulChecked(std::int64_t left, std::int64_t right, std::int64_t& result)
{
    return !__builtin_mul_overflow(left, right, &result);
}

bool AlignUpChecked(std::int64_t value, std::int64_t alignment, std::int64_t& result)
{
    std::int64_t units = 0;
    return CeilDivChecked(value, alignment, units) && MulChecked(units, alignment, result);
}

bool ComputeLoopAndTail(std::int64_t length, std::int64_t ubFormer, std::int64_t& loopCount, std::int64_t& tailCount)
{
    if (length <= 0 || !CeilDivChecked(length, ubFormer, loopCount) || loopCount <= 0) {
        return false;
    }
    std::int64_t formerTotal = 0;
    if (!MulChecked(loopCount - 1, ubFormer, formerTotal) || formerTotal >= length) {
        return false;
    }
    tailCount = length - formerTotal;
    return tailCount > 0 && tailCount <= ubFormer;
}

bool SetError(const char* message, const char*& errorMessage)
{
    errorMessage = message;
    return false;
}

