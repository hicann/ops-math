ge::graphStatus TilingFunc(gert::TilingContext* context)
{
    if (context == nullptr) {
        return TilingFailure("LogSpaceD", "tiling context is null");
    }
    Prepared prepared{};
    LogSpaceDCompileInfo compileInfo{};
    LogSpaceDTilingData computed{};
    if (Prepare(context, prepared) != ge::GRAPH_SUCCESS) {
        return TilingFailure(context->GetNodeName(), "input validation failed; see the preceding diagnostic");
    }
    if (ReadPlatform(context, compileInfo) != ge::GRAPH_SUCCESS) {
        return TilingFailure(context->GetNodeName(), "platform validation failed; see the preceding diagnostic");
    }
    if (ComputeCommon(context->GetNodeName(), prepared, compileInfo, computed) != ge::GRAPH_SUCCESS) {
        return TilingFailure(context->GetNodeName(), "tiling calculation failed; see the preceding diagnostic");
    }

    auto* tilingData = context->GetTilingData<LogSpaceDTilingData>();
    if (tilingData == nullptr) {
        return TilingFailure(context->GetNodeName(), "tiling data buffer is null");
    }
    *tilingData = computed;

    size_t* workspaceSizes = context->GetWorkspaceSizes(kWorkspaceCount);
    if (workspaceSizes == nullptr) {
        return TilingFailure(context->GetNodeName(), "workspace size buffer is null");
    }
    workspaceSizes[kWorkspaceIndex] = 0;
    if (context->SetSimdNumBlocks(static_cast<std::uint32_t>(computed.blockNum)) != ge::GRAPH_SUCCESS) {
        return TilingFailure(context->GetNodeName(), "failed to set SIMD block count");
    }
    if (context->SetTilingKey(GET_TPL_TILING_KEY(prepared.isEmpty)) != ge::GRAPH_SUCCESS) {
        return TilingFailure(context->GetNodeName(), "failed to set tiling key");
    }
    OP_LOGI(context->GetNodeName(),
            "LogSpaceD dtype=%u empty=%d dim0=%ld cores=%ld blocks=%ld blockFormer=%ld blockTail=%ld "
            "ubFormer=%ld loopsFormer=%ld tailFormer=%ld loopsTail=%ld tailTail=%ld storageBytes=%ld "
            "bufferBytes=%ld halfway=%ld start=%f end=%f step=%f logBase=%f "
            "stepLow=%f logBaseLow=%f base=%f workspace=0",
            static_cast<std::uint32_t>(prepared.inputType), prepared.isEmpty, static_cast<long>(computed.dim0),
            static_cast<long>(computed.coreNum), static_cast<long>(computed.blockNum),
            static_cast<long>(computed.blockFormer), static_cast<long>(computed.blockTail),
            static_cast<long>(computed.ubFormer), static_cast<long>(computed.ubLoopOfFormerBlock),
            static_cast<long>(computed.ubTailOfFormerBlock), static_cast<long>(computed.ubLoopOfTailBlock),
            static_cast<long>(computed.ubTailOfTailBlock), static_cast<long>(computed.storageElemBytes),
            static_cast<long>(computed.bufferBytesPerElem), static_cast<long>(computed.halfway), computed.start,
            computed.end, computed.step, computed.logBase, computed.stepLow, computed.logBaseLow, computed.base);
    return ge::GRAPH_SUCCESS;
}
