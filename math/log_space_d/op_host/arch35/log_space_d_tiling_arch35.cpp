ge::graphStatus TilingPrepare(gert::TilingParseContext* context)
{
    if (context == nullptr || context->GetPlatformInfo() == nullptr) {
        return TilingFailure("LogSpaceD", "platform parse context or platform info is null");
    }
    auto* compileInfo = context->GetCompiledInfo<LogSpaceDCompileInfo>();
    if (compileInfo == nullptr) {
        return TilingFailure("LogSpaceD", "compiled-info storage is null");
    }
    platform_ascendc::PlatformAscendC platform(context->GetPlatformInfo());
    compileInfo->availableCoreNum = platform.GetCoreNumAiv();
    platform.GetCoreMemSize(platform_ascendc::CoreMemType::UB, compileInfo->usableUbBytes);
    if (compileInfo->availableCoreNum == 0 || compileInfo->usableUbBytes == 0) {
        return TilingFailure("LogSpaceD", "platform reports zero AIV cores or zero UB bytes");
    }
    return ge::GRAPH_SUCCESS;
}

struct Prepared {
    ge::DataType inputType;
    std::int64_t outputElemBytes;
    std::int64_t steps;
    float start;
    float end;
    float base;
    bool isEmpty;
};

ge::graphStatus Prepare(gert::TilingContext* context, Prepared& prepared)
{
    const auto* inputDesc = context->GetInputDesc(kInputIndex);
    const auto* outputDesc = context->GetOutputDesc(kOutputIndex);
    if (inputDesc == nullptr || outputDesc == nullptr) {
        return InvalidInput(context->GetNodeName(), "input/output descriptor", "required descriptor is null");
    }

    prepared.inputType = inputDesc->GetDataType();
    switch (prepared.inputType) {
        case ge::DT_FLOAT16:
            break;
        case ge::DT_FLOAT:
            break;
        case ge::DT_BF16:
            break;
        default:
            OP_LOGE_FOR_INVALID_DTYPE(context->GetNodeName(), "assist", "unsupported", "DT_FLOAT16, DT_FLOAT, DT_BF16");
            return ge::GRAPH_FAILED;
    }

    if (inputDesc->GetOriginFormat() != ge::FORMAT_ND || inputDesc->GetStorageFormat() != ge::FORMAT_ND ||
        outputDesc->GetOriginFormat() != ge::FORMAT_ND || outputDesc->GetStorageFormat() != ge::FORMAT_ND) {
        OP_LOGE_FOR_INVALID_FORMAT_WITH_REASON(context->GetNodeName(), "assist/y", "non-ND",
                                               "input and output formats must be ND");
        return ge::GRAPH_FAILED;
    }

    const auto* inputShape = context->GetInputShape(kInputIndex);
    const auto* outputShape = context->GetOutputShape(kOutputIndex);
    if (inputShape == nullptr || outputShape == nullptr) {
        return InvalidInput(context->GetNodeName(), "input/output shape", "required shape is null");
    }
    const auto& inputOriginShape = inputShape->GetOriginShape();
    const auto& inputStorageShape = inputShape->GetStorageShape();
    const auto& outputOriginShape = outputShape->GetOriginShape();
    const auto& outputStorageShape = outputShape->GetStorageShape();
    if (inputOriginShape.GetDimNum() != 1 || inputStorageShape.GetDimNum() != 1 || outputOriginShape.GetDimNum() != 1 ||
        outputStorageShape.GetDimNum() != 1) {
        OP_LOGE_FOR_INVALID_SHAPEDIM_WITH_REASON(context->GetNodeName(), "assist/y", "rank is not 1",
                                                 "input and output tensors must be rank 1");
        return ge::GRAPH_FAILED;
    }

    const auto* attrs = context->GetAttrs();
    if (attrs == nullptr) {
        return InvalidInput(context->GetNodeName(), "runtime attributes", "required attributes are null");
    }
    const float* start = attrs->GetFloat(kStartAttrIndex);
    const float* end = attrs->GetFloat(kEndAttrIndex);
    const std::int64_t* steps = attrs->GetInt(kStepsAttrIndex);
    const float* base = attrs->GetFloat(kBaseAttrIndex);
    const std::int64_t* legacyDtype = attrs->GetInt(kDtypeAttrIndex);
    if (start == nullptr || end == nullptr || steps == nullptr || base == nullptr || legacyDtype == nullptr ||
        !std::isfinite(*start) || !std::isfinite(*end) || !std::isfinite(*base) || *steps < 0 ||
        (*legacyDtype != 0 && *legacyDtype != 1)) {
        OP_LOGE_FOR_INVALID_VALUE_WITH_REASON(context->GetNodeName(), "start/end/steps/base/dtype", "invalid",
                                              "attributes must be present, finite, and in range");
        return ge::GRAPH_FAILED;
    }
    prepared.outputElemBytes = prepared.inputType == ge::DT_FLOAT ? sizeof(float) : sizeof(std::uint16_t);
    if (outputDesc->GetDataType() != prepared.inputType) {
        OP_LOGE_FOR_INVALID_DTYPES_WITH_REASON(context->GetNodeName(), "assist/y", "input/output mismatch",
                                               "input and output dtypes must match");
        return ge::GRAPH_FAILED;
    }

    if (inputOriginShape.GetDim(0) != 1 || inputStorageShape.GetDim(0) != 1 || outputOriginShape.GetDim(0) != *steps ||
        outputStorageShape.GetDim(0) != *steps) {
        OP_LOGE_FOR_INVALID_SHAPE_WITH_REASON(context->GetNodeName(), "assist/y", "shape mismatch",
                                              "input must be [1] and output must be [steps]");
        return ge::GRAPH_FAILED;
    }

    prepared.steps = *steps;
    prepared.start = *start;
    prepared.end = *end;
    prepared.base = *base;
    prepared.isEmpty = (*steps == 0);
    return ge::GRAPH_SUCCESS;
}

ge::graphStatus ReadPlatform(gert::TilingContext* context, LogSpaceDCompileInfo& compileInfo)
{
    compileInfo = LogSpaceDCompileInfo{};
    auto* platformInfo = context->GetPlatformInfo();
    if (platformInfo != nullptr) {
        platform_ascendc::PlatformAscendC platform(platformInfo);
        compileInfo.availableCoreNum = platform.GetCoreNumAiv();
        platform.GetCoreMemSize(platform_ascendc::CoreMemType::UB, compileInfo.usableUbBytes);
    }
    if (compileInfo.usableUbBytes == 0 || compileInfo.availableCoreNum == 0) {
        const auto* supplied = context->GetCompileInfo<LogSpaceDCompileInfo>();
        if (supplied != nullptr) {
            compileInfo = *supplied;
        }
    }
    if (compileInfo.usableUbBytes == 0 || compileInfo.availableCoreNum == 0 ||
        compileInfo.usableUbBytes > static_cast<std::uint64_t>(std::numeric_limits<std::int64_t>::max())) {
        return TilingFailure(context->GetNodeName(), "platform and compile-info UB/core values are invalid");
    }
    return ge::GRAPH_SUCCESS;
}

ge::graphStatus ComputeCommon(const char* nodeName, const Prepared& prepared, const LogSpaceDCompileInfo& compileInfo,
                              LogSpaceDTilingData& tilingData)
{
    tilingData = LogSpaceDTilingData{};
    tilingData.dim0 = prepared.steps;
    if (prepared.isEmpty) {
        tilingData.coreNum = 1;
        tilingData.blockNum = 1;
        tilingData.storageElemBytes = prepared.outputElemBytes;
        tilingData.start = prepared.start;
        tilingData.end = prepared.end;
        tilingData.base = prepared.base;
        return ge::GRAPH_SUCCESS;
    }
    const LogSpaceDTilingInputs inputs{prepared.steps, compileInfo.availableCoreNum, compileInfo.usableUbBytes,
                                       prepared.outputElemBytes};
    const char* tilingError = nullptr;
    if (!ComputeLogSpaceDTiling(inputs, tilingData, tilingError)) {
        return TilingFailure(nodeName, tilingError == nullptr ? "unknown tiling calculation error" : tilingError);
    }

    tilingData.halfway = prepared.steps / 2;
    tilingData.start = prepared.start;
    tilingData.end = prepared.end;
    const float fp32Step = prepared.steps > 1 ?
                               (prepared.end - prepared.start) / static_cast<float>(prepared.steps - 1) :
                               prepared.end - prepared.start;
    const float fp32LogBase = prepared.base == 0.0F ? 0.0F : std::log(std::abs(prepared.base));
    // All supported signatures use the mandated FP32 compute path: subtract
    // the FP32 endpoints first, then divide in FP32, matching the main Golden.
    tilingData.step = fp32Step;
    tilingData.logBase = fp32LogBase;
    tilingData.stepLow = 0.0F;
    tilingData.logBaseLow = 0.0F;
    tilingData.base = prepared.base;
    // The sign of coreNum carries the three base branches; blockNum remains
    // the actual launch count.
    if (prepared.base < 0.0F) {
        tilingData.coreNum = -tilingData.coreNum;
    } else if (prepared.base == 0.0F) {
        tilingData.coreNum = 0;
    }
    return ge::GRAPH_SUCCESS;
}

