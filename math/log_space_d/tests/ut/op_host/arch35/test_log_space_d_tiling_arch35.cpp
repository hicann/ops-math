    ASSERT_EQ(second.tilingDataSize, sizeof(LogSpaceDTilingData));
    ASSERT_EQ(first.tilingKey, expectedTilingKey);
    ASSERT_EQ(first.blockNum, 1);
    ASSERT_EQ(first.workspaceSizes, std::vector<int64_t>({0}));
    EXPECT_EQ(std::memcmp(first.tilingData.get(), second.tilingData.get(), first.tilingDataSize), 0);

