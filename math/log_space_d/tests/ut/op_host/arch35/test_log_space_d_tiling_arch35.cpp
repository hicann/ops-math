TEST(LogSpaceDTilingArch35, C13ComputesFp32StepInFp32)
{
    constexpr float start = 9.327797889709473F;
    constexpr float end = -8.774908065795898F;
    constexpr int64_t steps = 4099;
    const float fp32Step = (end - start) / static_cast<float>(steps - 1);

    const std::vector<std::pair<ge::DataType, ge::DataType>> signatures = {
        {ge::DT_FLOAT16, ge::DT_FLOAT16}, {ge::DT_FLOAT, ge::DT_FLOAT}, {ge::DT_BF16, ge::DT_BF16}};
    for (const auto& signature : signatures) {
        optiling::LogSpaceDCompileInfo compileInfo = {USABLE_UB_BYTES, AVAILABLE_CORE_NUM};
        const int64_t dtype = signature.first == ge::DT_FLOAT ? DTYPE_FP32 : DTYPE_FP16;
        auto para = MakePara(signature.first, signature.second, {CARRIER_LENGTH}, {steps},
                             MakeAttrs(start, end, steps, BINARY_BASE, dtype), compileInfo);
        TilingInfo info;
        ASSERT_TRUE(ExecuteTiling(para, info));
        ASSERT_EQ(info.tilingDataSize, sizeof(LogSpaceDTilingData));
        const auto* tilingData = reinterpret_cast<const LogSpaceDTilingData*>(info.tilingData.get());
        ASSERT_NE(tilingData, nullptr);
        EXPECT_FLOAT_EQ(tilingData->step, fp32Step);
        EXPECT_FLOAT_EQ(tilingData->stepLow, 0.0F);
    }

    constexpr int64_t extremeSteps = 3;
    constexpr float extremeStart = -std::numeric_limits<float>::max();
    constexpr float extremeEnd = std::numeric_limits<float>::max();
    for (const auto& signature : signatures) {
        optiling::LogSpaceDCompileInfo compileInfo = {USABLE_UB_BYTES, AVAILABLE_CORE_NUM};
        const int64_t dtype = signature.first == ge::DT_FLOAT ? DTYPE_FP32 : DTYPE_FP16;
        auto para = MakePara(signature.first, signature.second, {CARRIER_LENGTH}, {extremeSteps},
                             MakeAttrs(extremeStart, extremeEnd, extremeSteps, BINARY_BASE, dtype), compileInfo);
        TilingInfo info;
        ASSERT_TRUE(ExecuteTiling(para, info));
        const auto* tilingData = reinterpret_cast<const LogSpaceDTilingData*>(info.tilingData.get());
        ASSERT_NE(tilingData, nullptr);
        EXPECT_TRUE(std::isinf(tilingData->step));
        EXPECT_FLOAT_EQ(tilingData->stepLow, 0.0F);
    }
}

TEST(LogSpaceDTilingArch35, C14ChecksRealMulticoreUbLoopsAndTails)
{
    constexpr uint32_t cores = 72;
    for (const auto type : {ge::DT_FLOAT16, ge::DT_FLOAT, ge::DT_BF16}) {
        const int64_t ub = type == ge::DT_FLOAT ? FP32_UB_FORMER : FP16_BF16_UB_FORMER;
        const int64_t former = ((ub + 1 + BLOCK_ALIGN_ELEMS - 1) / BLOCK_ALIGN_ELEMS) * BLOCK_ALIGN_ELEMS;
        for (const int64_t delta : {-1, 0, 1}) {
            const int64_t steps = (cores - 1) * former + ub + delta;
            optiling::LogSpaceDCompileInfo compileInfo = {USABLE_UB_BYTES, cores};
            auto para = MakePara(type, type, {1}, {steps}, MakeAttrs(-3.0F, 3.0F, steps, BINARY_BASE, 1), compileInfo);
            TilingInfo info;
            ASSERT_TRUE(ExecuteTiling(para, info));
            ASSERT_EQ(info.tilingDataSize, sizeof(LogSpaceDTilingData));
            const auto* data = reinterpret_cast<const LogSpaceDTilingData*>(info.tilingData.get());
            EXPECT_EQ(data->blockNum, cores);
            EXPECT_EQ(data->blockFormer, former);
            EXPECT_EQ(data->blockTail, ub + delta);
            EXPECT_EQ(data->ubLoopOfFormerBlock, 2);
            EXPECT_EQ(data->ubLoopOfTailBlock, delta == 1 ? 2 : 1);
            EXPECT_EQ(data->ubTailOfTailBlock, delta == 1 ? 1 : ub + delta);
            EXPECT_EQ(info.workspaceSizes, std::vector<int64_t>({0}));
        }
    }
}

